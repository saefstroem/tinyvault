package dev.tinyvault;

import java.nio.*;
import java.nio.charset.*;
import java.security.GeneralSecurityException;
import java.security.SecureRandom;
import java.util.Arrays;
import javax.crypto.Cipher;
import javax.crypto.spec.GCMParameterSpec;

public final class Vault {
    private static final int VERSION = 1;
    private static final int NONCE = 1, LENGTH = 13, TITLE = 15, TAG = 16;
    private static final SecureRandom RANDOM = new SecureRandom();

    public static byte[] seal(Cipher aes, String title, byte[] plaintext) throws GeneralSecurityException {
        try {
            byte[] name = title.getBytes(StandardCharsets.UTF_8); // convert title to. bytes
            if (name.length > 0xFFFF) throw new IllegalArgumentException("the title is longer than 65535 bytes");
            byte[] nonce = aes.getIV(); // read the nonce (it is randomly generated by android in add() call)
            // ensure there is a nonce
            if (nonce == null || nonce.length != LENGTH - NONCE) throw new GeneralSecurityException("the cipher has no 96-bit nonce");
            // create a header so that we can associate with a particular note
            byte[] header = ByteBuffer.allocate(TITLE + name.length).put((byte) VERSION).put(nonce).putShort((short) name.length)
                    .put(name).array();
            aes.updateAAD(header); // add the header as additional auth data
            byte[] sealed = aes.doFinal(plaintext); // encrypt the plaintext
            return ByteBuffer.allocate(header.length + sealed.length).put(header).put(sealed).array(); // create new buffer for encrypted
        } finally {
            // zeroize plaintext buffer
            Arrays.fill(plaintext, (byte) 0);
        }
    }

    // read title from some file
    public static String title(byte[] file) {
        return new String(file, TITLE, header(file) - TITLE, StandardCharsets.UTF_8);
    }

    // compute the nonce to be used for decryption by first checking the header
    public static GCMParameterSpec nonce(byte[] file) {
        header(file);
        return new GCMParameterSpec(TAG * 8, file, NONCE, LENGTH - NONCE);
    }

    // the mirrored operation of encryption, decryption with an already made aes cipher
    public static byte[] open(Cipher aes, byte[] file) throws GeneralSecurityException {
        int length = header(file); // validate header and get length
        aes.updateAAD(file, 0, length); // populate aad
        return aes.doFinal(file, length, file.length - length); // extract the plaintext
    }

    // validate the header of an encrypted note and return length of the header
    private static int header(byte[] file) {
        if (file.length < TITLE || file[0] != VERSION) throw new IllegalArgumentException("not a tinyvault note");
        int length = TITLE + (ByteBuffer.wrap(file).getShort(LENGTH) & 0xFFFF);
        if (length + TAG > file.length) throw new IllegalArgumentException("not a tinyvault note: cut short");
        return length;
    }

    // randomly generate a cryptographically secure password
    public static char[] password() {
        // create the charset used for password generation
        String consonants = "bcdfghjkmnprstvwxz", vowels = "aeiou";
        char[] password = new char[21]; // create password container
        int at = 0, numbered = RANDOM.nextInt(3); // create position index and randomized seed
        for (int word = 0; word < 3; word++) { // generate three words
            if (word > 0) password[at++] = '-'; // if it s a new word add hyphen
            for (int syllable = 0; syllable < 2; syllable++) { // generate two syllables per word
                password[at++] = consonants.charAt(RANDOM.nextInt(consonants.length())); // pick a random consonant
                password[at++] = vowels.charAt(RANDOM.nextInt(vowels.length())); // pick a random vowel
                password[at++] = consonants.charAt(RANDOM.nextInt(consonants.length())); // pick another random consonant
            }
            if (word == numbered) password[at++] = (char) ('2' + RANDOM.nextInt(8)); // add a random number to one of the words
        }
        int capital;
        do { capital = RANDOM.nextInt(password.length); } while (!Character.isLowerCase(password[capital])); // find a random lowercase character
        password[capital] = Character.toUpperCase(password[capital]); // capitalize the chosen character
        return password;
    }

    // convert a character array to a byte array using UTF-8 encoding
    public static byte[] bytes(char[] chars) {
        // allocate a byte buffer large enough to hold the UTF-8 encoded characters
        ByteBuffer out = ByteBuffer.allocate(chars.length * 3);
        // encode the characters into the byte buffer using UTF-8 encoding
        StandardCharsets.UTF_8.newEncoder().onMalformedInput(CodingErrorAction.REPLACE)
                .onUnmappableCharacter(CodingErrorAction.REPLACE).encode(CharBuffer.wrap(chars), out, true);
        // mark the end of input for the encoder and flush any remaining bytes
        Arrays.fill(chars, '\0');
        // create a copy that is exactly the size of the encoded bytes
        byte[] exact = Arrays.copyOf(out.array(), out.position());
        // zero out the original byte buffer to remove sensitive data
        Arrays.fill(out.array(), (byte) 0);
        return exact;
    }

    // convert a byte array to a character array using UTF-8 decoding
    public static char[] chars(byte[] bytes) {
        // allocate a character buffer large enough to hold the decoded characters
        CharBuffer out = CharBuffer.allocate(bytes.length);
        // decode the bytes into the character buffer using UTF-8 decoding
        StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPLACE)
                .onUnmappableCharacter(CodingErrorAction.REPLACE).decode(ByteBuffer.wrap(bytes), out, true);
        // zero out the original byte array to remove sensitive data
        Arrays.fill(bytes, (byte) 0);
        // create a copy that is exactly the size of the decoded characters
        char[] exact = Arrays.copyOf(out.array(), out.position());
        // zero out the original character buffer to remove sensitive data
        Arrays.fill(out.array(), '\0');
        return exact;
    }
}
